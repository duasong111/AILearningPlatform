# Redis Cache
#
# 公网 Redis 的 idle 连接会被远端主动 kill；django_redis 默认 SOCKET_TIMEOUT=None
# (无限等)，那种死连接下次再用会卡到 TCP 系统 timeout（几分钟），
# 直接拖死 daphne 的 ASGI worker → 浏览器看到 "timeout of 30000ms exceeded"。
# 这里：
#   - SOCKET_CONNECT_TIMEOUT=5  建连最多 5s
#   - SOCKET_TIMEOUT=5          单次 read/write 最多 5s
#   - IGNORE_EXCEPTIONS=True    cache 失败不抛，返回 None；business state 写不进
#                              Redis 也不该把 HTTP view 整个干掉（Celery worker 那边
#                              还会自己写一遍，最坏只是少了 meta 缓存）
CACHES = {
    'default': {
        'BACKEND': 'django_redis.cache.RedisCache',
        'LOCATION': os.getenv('REDIS_URL', 'redis://localhost:6379/0'),
        'OPTIONS': {
            'CLIENT_CLASS': 'django_redis.client.DefaultClient',
            'SOCKET_CONNECT_TIMEOUT': 5,
            'SOCKET_TIMEOUT': 5,
            'IGNORE_EXCEPTIONS': True,
        }
    }
}
# 全局生效 —— 等价于在每个 cache backend OPTIONS 写 IGNORE_EXCEPTIONS=True，
# 但有这一行后即使别的 cache backend 没写也会被忽略
DJANGO_REDIS_IGNORE_EXCEPTIONS = True


